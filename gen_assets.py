"""Embeds the logo and the Excel template into JavaScript modules (src/11-logo.js, src/12-template.js)."""
import base64, json, os
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
def b64(p):
    return base64.b64encode(open(os.path.join(ROOT, p), 'rb').read()).decode()
with open(os.path.join(ROOT, 'src', '11-logo.js'), 'w') as f:
    f.write("/* Regen Renewables logo (generated by scripts/gen_assets.py from assets/logo) */\n")
    f.write("const LOGO = { full: 'data:image/png;base64,%s', mark: 'data:image/png;base64,%s' };\n" % (b64('assets/logo/regen_logo.png'), b64('assets/logo/regen_mark.png')))
with open(os.path.join(ROOT, 'src', '12-template.js'), 'w') as f:
    f.write("/* Excel workbook template + cell map (generated by scripts/gen_assets.py from workbook/) */\n")
    f.write("const XL_TPL = '%s';\n" % b64('workbook/template_raw.xlsx'))
    f.write("const XL_MAP = %s;\n" % json.dumps(json.load(open(os.path.join(ROOT, 'workbook', 'cellmap.json')))))
print('src/11-logo.js and src/12-template.js written')
